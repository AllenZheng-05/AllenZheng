/** SVG path data for one character drawn into the box (x, y, w, h). '' for an unknown character. */
export function glyphPath(ch: string, x: number, y: number, w: number, h: number, pad = 0): string {
  const g = PARSED[ch]
  if (!g) return ''
  const sx = (w - 2 * pad) / 100
  const sy = (h - 2 * pad) / 100
  let d = ''
  for (const s of g) {
    d +=
      'M' +
      s
        .map(
          ([px = 0, py = 0]) =>
            (x + pad + px * sx).toFixed(1) + ' ' + (y + pad + py * sy).toFixed(1),
        )
        .join('L')
  }
  return d
}
